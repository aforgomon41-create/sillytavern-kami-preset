import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createKamiSearchTaskBinding} from '../../src/scripts/_search-task.js';
const preset=JSON.parse(fs.readFileSync(new URL('../../src/preset.base.json',import.meta.url))),definition=preset.prompts.find(x=>x.identifier==='kami_web_search_task');
const header='prompt_1789213927315_4s0dsfk';let saves=0,fail=false,count=0;
const raw={ok:true,settings:{prompts:[{identifier:header,content:'保留头部'},{identifier:'other',content:'保留用户修改'}]},order:{order:[{identifier:header,enabled:true},{identifier:'other',enabled:true}]}};
const eq=(a,b,label)=>{assert.deepEqual(a,b,label);count++};
const task=createKamiSearchTaskBinding({read:()=>raw,mirror(){},save(){if(fail)throw Error('保存失败');saves++;}},definition);
eq(task.read(),null);
task.ensure({enabled:true,content:definition.content});
eq(raw.order.order.map(x=>x.identifier),[header,definition.identifier,'other'],'迁移到头部任务区，不乱放到正文后');
eq(raw.settings.prompts[2].content,'保留用户修改');eq(task.read().enabled,true);eq(saves,1);
task.write({enabled:false,content:'用户在工具箱修改的完整任务'});eq(task.read(),{enabled:false,content:'用户在工具箱修改的完整任务'});
eq(raw.settings.prompts[1].enabled,false);eq(raw.order.order[1].enabled,false);
const saved=saves;task.write({enabled:false,content:'用户在工具箱修改的完整任务'});eq(saves,saved,'无变更不重复保存');
raw.settings.prompts[1].content='用户直接编辑条目';raw.order.order[1].enabled=true;eq(task.read(),{enabled:true,content:'用户直接编辑条目'});
fail=true;assert.throws(()=>task.write({enabled:false,content:'无法保存的修改'}),/保存失败/);count++;
eq(task.read(),{enabled:true,content:'用户直接编辑条目'},'保存失败恢复当前条目');
const order=preset.prompt_order.find(x=>x.character_id===100001).order;eq(order.find(x=>x.identifier===definition.identifier).enabled,false,'发布默认关闭');
eq(order.findIndex(x=>x.identifier===definition.identifier),order.findIndex(x=>x.identifier===header)+1,'正式条目放在头部任务首项');
assert.ok(definition.content.includes('<search_results>')&&definition.content.includes('[1]'));count++;
assert.match(definition.content,/^\{\{\/\/[\s\S]+?\}\}\s*<web_search_task>/);count++;
assert.match(definition.content,/<\/web_search_task>\s*$/);count++;
eq(preset.prompts.some(p=>p.identifier==='72e10746-4da8-4c7f-a0f6-57d9c01a8113'),false);
eq(preset.prompt_order.some(group=>group.order.some(p=>p.identifier==='72e10746-4da8-4c7f-a0f6-57d9c01a8113')),false,'占位条目和全部顺序引用一起删除');
let cache = { enabled: true, content: '旧内容' };
const mirrored=createKamiSearchTaskBinding({read:()=>raw,mirror(_raw,p,o){const before={...cache};cache={enabled:o.enabled,content:p.content};return()=>{cache=before;};},save(){throw Error('失败');}},definition);
assert.throws(()=>mirrored.write({enabled:false,content:'无法保存'}));count++;
eq(cache,{enabled:true,content:'旧内容'},'保存失败同步回滚预设缓存');
console.log('网络搜索头部任务绑定：'+count+' 项通过');
